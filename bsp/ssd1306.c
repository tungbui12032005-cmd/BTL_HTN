static void set_pin(uint32_t pin, bool release)
{
    GPIOB->BSRR = release ? pin : pin << 16;
    board_wait_us(3);
}

static bool send_byte(uint8_t byte)
{
    for (unsigned bit = 0; bit < 8U; ++bit) {
        set_pin(SDA, (byte & 0x80U) != 0);
        set_pin(SCL, true);
        set_pin(SCL, false);
        byte <<= 1;
    }
    set_pin(SDA, true);
    set_pin(SCL, true);
    bool ack = !(GPIOB->IDR & SDA);
    set_pin(SCL, false);
    return ack;
}

static bool transfer(uint8_t control, const uint8_t *data, size_t length)
{
    set_pin(SDA, true);
    set_pin(SCL, true);
    if ((GPIOB->IDR & (SCL | SDA)) != (SCL | SDA)) return false;
    set_pin(SDA, false);
    set_pin(SCL, false);

    bool ack = send_byte(OLED_ADDRESS << 1) && send_byte(control);
    for (size_t i = 0; ack && i < length; ++i) ack = send_byte(data[i]);

    set_pin(SDA, false);
    set_pin(SCL, true);
    set_pin(SDA, true);
    return ack;
}

bool ssd1306_init(void)
{
    static const uint8_t init[] = {
        0xae,0xd5,0x80,0xa8,0x3f,0xd3,0,0x40,0x8d,0x14,0x20,0,
        0xa1,0xc8,0xda,0x12,0x81,0x7f,0xd9,0xf1,0xdb,0x40,0xa4,0xa6,0x2e,0xaf
    };
    GPIOB->BSRR = SCL | SDA;
    GPIOB->CRL = (GPIOB->CRL & 0x00ffffffU) | 0x66000000U;
    return transfer(0, init, sizeof init);
}

void ssd1306_clear(void) { memset(pixels, 0, sizeof pixels); }

static const uint8_t *glyph(char ch)
{
    static const uint8_t space[5] = {0};
    static const uint8_t colon[5] = {0,0x36,0x36,0,0};
    static const uint8_t dash[5] = {8,8,8,8,8};
    static const uint8_t slash[5] = {0x20,0x10,8,4,2};
    if (ch >= '0' && ch <= '9') return digits[ch - '0'];
    if (ch >= 'A' && ch <= 'Z') return letters[ch - 'A'];
    if (ch == ':') return colon;
    if (ch == '-') return dash;
    if (ch == '/') return slash;
    return space;
}

void ssd1306_text(unsigned row, unsigned column, const char *text)
{
    if (row >= 8U) return;
    while (*text && column <= 122U) {
        memcpy(&pixels[row * 128U + column], glyph(*text++), 5);
        pixels[row * 128U + column + 5U] = 0;
        column += 6U;
    }
}

bool ssd1306_show(void)
{
    static const uint8_t area[] = {0x21,0,127,0x22,0,7};
    return transfer(0, area, sizeof area) && transfer(0x40, pixels, sizeof pixels);
}
